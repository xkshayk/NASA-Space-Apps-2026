"""Convert official source products into documented browser assets.

Outputs (ignored by Git, regenerated by setup):
- moon.jpg: NASA/GSFC/ASU LROC colour mosaic (appearance only).
- moon-height.f32: LOLA heights averaged over 0.5 degree cells for the render mesh.
- moon-normal.jpg: tangent-space normals from the LOLA residual below 0.5 degrees,
  so fine crater shading responds to the real Sun direction without
  double-counting the mesh relief. No vertical exaggeration; display only.
- moon-south-normal.jpg: south polar cap normals from the 240 m LOLA DEM on a
  polar-stereographic grid, replacing the pinched equirectangular shading near
  the pole where the CLPS south-pole sites are. Display only.
- earth.png: NASA Blue Marble mosaic.
"""
from pathlib import Path
import json
import math
import shutil
import numpy as np
import rasterio
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
RADIUS_KM = 1737.4
BLOCK = 8            # 1/16 degree source pixels -> 0.5 degree mesh cells
NORMAL_SIZE = (4096, 2048)

def block_mean(heights, block):
    rows, cols = heights.shape
    return heights.reshape(rows//block, block, cols//block, block).mean(axis=(1, 3))

def upsample_cells(cells, shape, block):
    """Bilinear interpolation between cell centres; longitude wraps, latitude clamps."""
    rows, cols = cells.shape
    ys = (np.arange(shape[0]) + .5)/block - .5
    xs = (np.arange(shape[1]) + .5)/block - .5
    y0f, x0f = np.floor(ys), np.floor(xs)
    fy, fx = (ys-y0f)[:, None], (xs-x0f)[None, :]
    y0 = np.clip(y0f, 0, rows-1).astype(int); y1 = np.clip(y0f+1, 0, rows-1).astype(int)
    x0 = x0f.astype(int) % cols; x1 = (x0+1) % cols
    top = (1-fx)*cells[y0][:, x0] + fx*cells[y0][:, x1]
    bottom = (1-fx)*cells[y1][:, x0] + fx*cells[y1][:, x1]
    return (1-fy)*top + fy*bottom

def tangent_normals(residual_km, pixel_deg):
    """Unit normals (east, north, up) of a height field on the sphere, east-positive longitude."""
    rows = residual_km.shape[0]
    lat = 90 - (np.arange(rows) + .5)*pixel_deg
    spacing = math.radians(pixel_deg)*RADIUS_KM
    # Near the poles equirectangular pixels collapse in longitude; clamping keeps
    # the display shading stable there instead of amplifying sampling noise.
    east_spacing = spacing*np.maximum(np.cos(np.radians(lat)), .05)[:, None]
    d_east = (np.roll(residual_km, -1, axis=1) - np.roll(residual_km, 1, axis=1))/(2*east_spacing)
    d_north = np.gradient(residual_km, axis=0)/(-spacing)  # row index increases southward
    normal = np.stack([-d_east, -d_north, np.ones_like(residual_km)], axis=-1)
    return normal/np.linalg.norm(normal, axis=-1, keepdims=True)

def polar_normals(heights, cell):
    """(east, north, up) unit normals for a square south-polar-stereographic height grid
    centred on the pole: x = rho sin(lon), y = rho cos(lon); rows run from +y to -y."""
    size = heights.shape[0]
    d_x = np.gradient(heights, cell, axis=1)   # +x: increasing column
    d_y = -np.gradient(heights, cell, axis=0)  # +y: decreasing row
    centers = (np.arange(size) + .5 - size/2)*cell
    x, y = np.meshgrid(centers, -centers)
    lon = np.arctan2(x, y)
    # Away from the south pole is north; east is 90° clockwise from it in the x/y plane.
    east = -d_x*np.cos(lon) + d_y*np.sin(lon)
    north = -d_x*np.sin(lon) - d_y*np.cos(lon)
    normal = np.stack([east, north, np.ones_like(d_x)], axis=-1)
    return normal/np.linalg.norm(normal, axis=-1, keepdims=True)

def south_cap(out, color_rgb):
    """Normals for the south polar cap from the 240 m polar-stereographic LOLA DEM.

    The equirectangular global maps pinch at the pole, exactly where the CLPS
    south-pole sites are. Here each pixel stores (east, north, up) normal
    components on a polar-stereographic grid that the browser samples directly.
    """
    edge_lat = -74.0
    rho_max = 2*RADIUS_KM*1000*math.tan(math.radians(90 + edge_lat)/2)  # metres from the pole
    with rasterio.open(ROOT/'data/raw/south-dem.tif') as src:
        t = src.transform
        pixel = t.a
        half = int(math.ceil(rho_max/pixel/2))*2
        center_col, center_row = round(-t.c/pixel), round(t.f/pixel)
        window = rasterio.windows.Window(center_col-half, center_row-half, 2*half, 2*half)
        heights = src.read(1, window=window).astype(np.float32)*src.scales[0] + src.offsets[0]
    if not np.isfinite(heights).all():
        raise ValueError('South polar DEM has gaps inside the display cap; no synthetic fill is used')
    normal = polar_normals(heights, pixel)  # native 240 m cells
    encoded = np.clip(np.round((normal*.5 + .5)*255), 0, 255).astype(np.uint8)
    Image.fromarray(encoded).resize((4096, 4096), Image.LANCZOS).save(out/'moon-south-normal.jpg', quality=88, subsampling=0)
    # Neutral polar albedo: the LROC mosaic is smeared near the pole, so the
    # display fades to the mean colour of the -72° to -80° band (linear RGB).
    rows = color_rgb.shape[0]
    band = color_rgb[int((90+72)/180*rows):int((90+80)/180*rows)].reshape(-1, 3)/255.0
    linear = np.where(band <= .04045, band/12.92, ((band + .055)/1.055)**2.4).mean(axis=0)
    return {'file': 'moon-south-normal.jpg', 'size': [4096, 4096], 'edgeLatitudeDeg': edge_lat,
            'rhoMaxRadii': rho_max/(RADIUS_KM*1000), 'cellM': pixel, 'albedoLinear': [round(float(v), 5) for v in linear],
            'content': 'east, north, up normal components from LDEM_60S_240MPP_ADJ at its native 240 m spacing; display only',
            'source': 'https://pgda.gsfc.nasa.gov/products/90'}

def main():
    out = ROOT/'web/public/assets'
    out.mkdir(parents=True, exist_ok=True)
    with rasterio.open(ROOT/'data/raw/moon-color.tif') as src:
        rgb = np.moveaxis(src.read()[:3], 0, -1)
        if rgb.dtype == np.uint16: rgb = (rgb/257).round().astype('uint8')
        Image.fromarray(rgb).save(out/'moon.jpg', quality=94)
    cap = south_cap(out, np.asarray(Image.open(out/'moon.jpg')))
    shutil.copy2(ROOT/'data/raw/earth.png', out/'earth.png')
    with rasterio.open(ROOT/'data/raw/moon-dem.tif') as src:
        heights = src.read(1).astype(np.float32)
    pixel_deg = 180/heights.shape[0]
    # Actual relief, no exaggeration: cell means for the mesh, the residual for shading.
    cells = block_mean(heights, BLOCK).astype('<f4')
    cells.tofile(out/'moon-height.f32')
    residual = heights - upsample_cells(cells, heights.shape, BLOCK)
    normals = tangent_normals(residual.astype(np.float32), pixel_deg)
    encoded = np.clip(np.round((normals*.5 + .5)*255), 0, 255).astype(np.uint8)
    Image.fromarray(encoded).resize(NORMAL_SIZE, Image.LANCZOS).save(out/'moon-normal.jpg', quality=90, subsampling=0)
    (out/'moon-height.png').unlink(missing_ok=True)  # Obsolete 24 MB asset from earlier setups.
    (out/'terrain.json').write_text(json.dumps({
        'width': cells.shape[1], 'height': cells.shape[0], 'units': 'km', 'referenceRadiusKm': RADIUS_KM,
        'sourceResolutionDegrees': pixel_deg, 'meshResolutionDegrees': pixel_deg*BLOCK,
        'meshSampling': f'{BLOCK}x{BLOCK} block mean; browser interpolates between cell centres',
        'normalMap': {'file': 'moon-normal.jpg', 'size': list(NORMAL_SIZE), 'content': 'tangent-space normals (east, north, up) of LOLA relief finer than the mesh'},
        'southCap': cap,
        'source': 'https://svs.gsfc.nasa.gov/4720/', 'exaggeration': 1}, indent=2))
    print('Prepared NASA textures, unexaggerated LOLA mesh heights and surface normals in web/public/assets')

if __name__ == '__main__':
    main()
